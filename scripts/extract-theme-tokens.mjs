// Reads the design tokens of the built-in LIGHT and DARK themes from a running
// Web SDK viewer and writes them to src/theme/tokens.js.
//
// A custom theme object must contain every token (the Web SDK does not merge a
// partial theme with a built-in one), so the playground derives its brand
// themes from these two complete token sets. Run this again after an SDK upgrade:
//
//   npm run theme-tokens
//
// The Web SDK applies the theme as CSS variables (`--bui-*`) on the element with
// the public class `BaselineUI-ThemeProvider`; each theme property maps to one
// variable, for example color.background.primary.strong is
// --bui-color-background-primary-strong.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const SDK_VERSION = "1.24.0";
const root = fileURLToPath(new URL("..", import.meta.url));
const pdf = await readFile(`${root}public/documents/field-service-handbook.pdf`);

const html = `<!doctype html><html><head><meta charset="utf-8">
<script src="https://cdn.cloud.pspdfkit.com/pspdfkit-web@${SDK_VERSION}/nutrient-viewer.js"></script>
</head><body style="margin:0"><div id="viewer" style="position:absolute;inset:0"></div></body></html>`;

// "letter-spacing" -> "letterSpacing", "2-xl" -> "2xl", "h-6" -> "h6"
function variableToPath(name) {
  const parts = name.replace(/^--bui-/, "").split("-");
  const path = [];
  for (let i = 0; i < parts.length; i++) {
    const part = parts[i];
    const next = parts[i + 1];
    if (part === "letter" && next === "spacing") { path.push("letterSpacing"); i++; }
    else if (/^\d+$/.test(part) && next === "xl") { path.push(`${part}xl`); i++; }
    else if (part === "h" && /^\d$/.test(next)) { path.push(`h${next}`); i++; }
    else path.push(part);
  }
  return path;
}

function nest(entries) {
  const out = {};
  for (const [path, value] of entries) {
    let node = out;
    path.slice(0, -1).forEach((key) => { node = node[key] ??= {}; });
    node[path.at(-1)] = value;
  }
  return out;
}

const browser = await chromium.launch();
const page = await browser.newPage();
await page.route("http://tokens.local/**", (route) => route.fulfill({ contentType: "text/html", body: html }));
await page.goto("http://tokens.local/");

const themes = {};
for (const theme of ["LIGHT", "DARK"]) {
  const style = await page.evaluate(async ({ theme, bytes, version }) => {
    try { NutrientViewer.unload("#viewer"); } catch { /* nothing loaded yet */ }
    const instance = await NutrientViewer.load({
      container: "#viewer",
      document: new Uint8Array(bytes).buffer,
      baseUrl: `https://cdn.cloud.pspdfkit.com/pspdfkit-web@${version}/`,
      theme: NutrientViewer.Theme[theme],
    });
    return instance.contentDocument.querySelector(".BaselineUI-ThemeProvider").getAttribute("style");
  }, { theme, bytes: [...pdf], version: SDK_VERSION });

  const entries = style
    .split(";")
    .map((declaration) => declaration.trim())
    .filter((declaration) => declaration.startsWith("--bui-"))
    .map((declaration) => {
      const index = declaration.indexOf(":");
      return [variableToPath(declaration.slice(0, index).trim()), declaration.slice(index + 1).trim()];
    });
  themes[theme] = nest(entries);
  console.log(`${theme}: ${entries.length} tokens`);
}
await browser.close();

const banner = `// Generated by scripts/extract-theme-tokens.mjs from Nutrient Web SDK ${SDK_VERSION}.
// Complete token sets of the built-in LIGHT and DARK themes. Do not edit by hand.
`;
const body = Object.entries(themes)
  .map(([name, tokens]) => `export const ${name} = ${JSON.stringify(tokens, null, 2)};\n`)
  .join("\n");
await writeFile(`${root}src/theme/tokens.js`, `${banner}\n${body}`);
console.log("Wrote src/theme/tokens.js");
