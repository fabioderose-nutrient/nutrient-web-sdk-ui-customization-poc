function indentBlock(text, spaces) {
  const pad = " ".repeat(spaces);
  return text.split("\n").map((line) => (line ? pad + line : line)).join("\n");
}

function viewerJs(state) {
  const header = [
    "// Generated by the Nutrient Web SDK UI customization playground.",
    `// Nutrient Web SDK ${SDK_VERSION}. index.html loads it from the CDN. With npm, use`,
    '// `import NutrientViewer from "@nutrient-sdk/viewer";` and set baseUrl to where you serve the SDK assets.',
    "// No licenseKey is set, so the viewer runs in evaluation mode. Add `licenseKey` for production.",
  ];
  const lines = [...header];
  if (state.theme === "CUSTOM") lines.push("", 'import { brandTheme } from "./brand-theme.js";');
  lines.push("", "let instance = null;");

  const snippets = snippetSources(state);
  if (snippets.length) lines.push("", snippets.map((snippet) => snippet.code).join("\n\n"));

  lines.push("", `instance = await NutrientViewer.load(${print(loadTree(state, {}), 0)});`);

  const after = postLoadCalls(state);
  if (after.length) lines.push("", ...after.map((item) => item.code));
  return `${lines.join("\n")}\n`;
}

function indexHtml(state) {
  const controls = state.externalControls;
  const style = [
    "      body { margin: 0; height: 100vh; display: flex; flex-direction: column; font-family: system-ui, sans-serif; }",
    "      #viewer { flex: 1; position: relative; }",
  ];
  if (controls) style.push(indentBlock(EXTERNAL_CONTROLS_CSS, 6));
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>Document viewer</title>
    <script src="${SDK_SCRIPT_URL}"></script>
    <style>
${style.join("\n")}
    </style>
  </head>
  <body>
${controls ? `${indentBlock(EXTERNAL_CONTROLS_HTML, 4)}\n` : ""}    <div id="viewer"></div>
    <script type="module" src="viewer.js"></script>
  </body>
</html>
`;
}

function brandThemeJs(state) {
  const theme = buildBrandTheme({
    base: state.themeBase, accent: state.accent, surfaceTint: state.surfaceTint, font: state.font, corners: state.corners,
  });
  return `// Custom theme for the Nutrient Web SDK \`theme\` option.
// The SDK needs the complete object: every token of the theme contract must be present.
// Built from the ${state.themeBase} theme tokens with accent ${state.accent}, surface tint ${state.surfaceTint}%,
// ${state.corners} corners and the "${FONTS[state.font].label}" font.
export const brandTheme = ${printTheme(theme)};
`;
}

function overridesCss(state) {
  return `/* Loaded into the viewer with the styleSheets option. Use the public PSPDFKit-* and BaselineUI-* classes. */
${safeCss(state.customCss).trim()}
`;
}

export function generateFiles(state) {
  const files = [
    { name: "viewer.js", language: "js", content: viewerJs(state) },
    { name: "index.html", language: "html", content: indexHtml(state) },
  ];
  if (state.theme === "CUSTOM") files.push({ name: "brand-theme.js", language: "js", content: brandThemeJs(state) });
  if (state.customCss.trim()) files.push({ name: "viewer-overrides.css", language: "css", content: overridesCss(state) });
  return files;
}
